#!/usr/bin/env python3
"""Writes Formula/caudra.rb for the newest published Caudra release, previews included.

The checksums come from the release's sha256sums.txt, the same manifest the official
installer verifies. Run without arguments for the newest release, or pass a tag.
"""

from __future__ import annotations

import json
import os
import re
import sys
import urllib.request
from pathlib import Path

REPO = "caudra/caudra"
API = f"https://api.github.com/repos/{REPO}"
DOWNLOAD = f"https://github.com/{REPO}/releases/download"
FORMULA = Path(__file__).resolve().parent.parent / "Formula" / "caudra.rb"
TARGETS = {
    "macos_arm": "aarch64-apple-darwin",
    "macos_intel": "x86_64-apple-darwin",
    "linux_arm": "aarch64-unknown-linux-musl",
    "linux_intel": "x86_64-unknown-linux-musl",
}
TAG = re.compile(r"^v(\d+\.\d+\.\d+(?:-[0-9A-Za-z.]+)?)$")
SHA256 = re.compile(r"^[0-9a-f]{64}$")


def get(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json", "User-Agent": "caudra-homebrew-tap"})
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if token and url.startswith("https://api.github.com/"):
        request.add_header("Authorization", f"Bearer {token}")
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def newest_tag() -> str:
    releases = json.loads(get(f"{API}/releases?per_page=20"))
    for release in releases:
        if not release["draft"] and TAG.match(release["tag_name"]):
            return release["tag_name"]
    raise SystemExit("no published release found")


def checksums(tag: str) -> dict[str, str]:
    sums: dict[str, str] = {}
    for line in get(f"{DOWNLOAD}/{tag}/sha256sums.txt").decode().splitlines():
        digest, _, name = line.strip().partition("  ")
        if SHA256.match(digest) and name:
            sums[name] = digest
    return sums


def render(tag: str, sums: dict[str, str]) -> str:
    match = TAG.match(tag)
    if not match:
        raise SystemExit(f"{tag} is not a release tag")
    version = match.group(1)
    entry: dict[str, tuple[str, str]] = {}
    for key, target in TARGETS.items():
        archive = f"caudra-{tag}-{target}.tar.gz"
        if archive not in sums:
            raise SystemExit(f"{tag} has no checksum for {archive}")
        entry[key] = (f"{DOWNLOAD}/{tag}/{archive}", sums[archive])

    def block(key: str) -> str:
        url, digest = entry[key]
        return f'      url "{url}"\n      sha256 "{digest}"'

    return f'''# Generated by scripts/update_formula.py from the {tag} release. Do not edit by hand.
class Caudra < Formula
  desc "Complete coding agent for your terminal"
  homepage "https://caudra.ai"
  version "{version}"
  license "Apache-2.0"

  on_macos do
    on_arm do
{block("macos_arm")}
    end
    on_intel do
{block("macos_intel")}
    end
  end

  on_linux do
    on_arm do
{block("linux_arm")}
    end
    on_intel do
{block("linux_intel")}
    end
  end

  def install
    bin.install "caudra"
    (pkgshare/"licenses").install Dir["licenses/*"]
  end

  def caveats
    <<~EOS
      Update and roll back Caudra through Homebrew: brew upgrade caudra
    EOS
  end

  test do
    assert_match "caudra #{{version}}", shell_output("#{{bin}}/caudra --version")
  end
end
'''


def main(args: list[str]) -> None:
    tag = args[0] if args else newest_tag()
    formula = render(tag, checksums(tag))
    if FORMULA.exists() and FORMULA.read_text() == formula:
        print(f"Formula/caudra.rb is already at {tag}")
        return
    FORMULA.parent.mkdir(parents=True, exist_ok=True)
    FORMULA.write_text(formula)
    print(f"Formula/caudra.rb now installs {tag}")


if __name__ == "__main__":
    main(sys.argv[1:])
